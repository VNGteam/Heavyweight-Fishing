            if type(callback) == "function" then pcall(callback, tb.Text) end
        end,
        Get = function() return tb.Text end
    }

    local mappedKey = State.ConfigLabelMap[labelText]
    if mappedKey then
        State.UIControllers[mappedKey] = ret
    end
    return ret
end

